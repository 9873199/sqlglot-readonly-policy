"""
Fail-closed read-access analysis for untrusted queries.

This module answers one question without ever executing the input: *which physical
tables would this query read?*  It is built on top of :mod:`sqlglot.optimizer.scope`,
so CTEs, derived tables, recursive CTEs, correlated subqueries and set operations
are resolved by the same machinery the optimizer uses rather than by collecting
``exp.Table`` nodes from the whole tree.

Design rules:

* Only a single, read-only ``exp.Query`` statement is accepted.
* Table sources are resolved through the scope graph. A CTE or derived table that
  happens to share a name with a physical table *shadows* the physical table; the
  CTE body is analysed instead, so an authorized-looking name cannot smuggle in an
  unauthorized source.
* All CTE bodies are analysed, even ones that are not referenced. This is
  deliberately conservative: an unreferenced definition must not become a
  smuggling channel, and engines differ in when they bind such definitions.
* Every physical table reference is completed with the caller-supplied default
  catalog/schema using one uniform rule and checked against the allow-list. An
  omitted component with no configured default is a rejection, not a guess.
* Identifier resolution follows the dialect's real rules. DuckDB treats identifiers
  case-insensitively even when quoted, so quoted and unquoted spellings resolve to
  the same source; SQLGlot `case_sensitive` meta comments are ignored.
* Table-valued functions, unapproved scalar functions, external/file scans, and any
  source whose identity cannot be determined are rejected. The analyzer makes no
  claim about side effects of arbitrary user functions: if it is not explicitly
  allow-listed, it is rejected.
* Any parsing or scope-building failure is a rejection. It never degrades into an
  empty access set that a caller could mistake for "no tables read".

The analyzer has no database connection and performs no I/O.

Example (no database connection is opened)::

    from sqlglot.optimizer.read_access import (
        ReadPolicy,
        TableRef,
        analyze_read_access,
    )

    policy = ReadPolicy(
        allowed_tables={("memory", "main", "sales")},
        default_catalog="memory",
        default_schema="main",
        allowed_functions={"sum"},
    )
    result = analyze_read_access(
        "WITH total AS (SELECT SUM(amount) AS n FROM sales) SELECT * FROM total",
        policy,
    )
    if not result.ok:
        raise PermissionError(result.reason)
    assert result.tables == frozenset({TableRef("memory", "main", "sales")})
"""

